const pluralDe = {
	'%n file::_%n files': ['%n Datei', '%n Dateien'],
	'%n image::_%n images': ['%n Bild', '%n Bilder'],
	'%n item selected::_%n items selected': ['%n Element ausgewählt', '%n Elemente ausgewählt'],
	'%n gallery::_%n galleries': ['%n Galerie', '%n Galerien'],
}

const sources = await Promise.all(sourceFiles.map(file => readFile(path.join(root, file), 'utf8')))
const singular = new Set()
const plurals = new Map()
for (const source of sources) {
	for (const match of source.matchAll(/\bt\(\s*'proofing_gallery'\s*,\s*'([^']+)'/g)) {
		singular.add(match[1])
	}
	for (const match of source.matchAll(/\$l->t\(\s*'([^']+)'/g)) {
		singular.add(match[1])
	}
	for (const match of source.matchAll(/\bn\(\s*'proofing_gallery'\s*,\s*'([^']+)'\s*,\s*'([^']+)'/g)) {
		plurals.set(`${match[1]}::_${match[2]}`, [match[1], match[2]])
	}
}

const missing = [...singular].filter(key => !(key in de))
if (missing.length > 0) {
	throw new Error(`Missing German translations:\n${missing.join('\n')}`)
}
for (const key of plurals.keys()) {
	if (!(key in pluralDe)) throw new Error(`Missing German plural translation: ${key}`)
}

const sorted = entries => Object.fromEntries([...entries].sort(([left], [right]) => left.localeCompare(right)))
const english = sorted([
	...[...singular].map(key => [key, key]),
	...[...plurals].map(([key, forms]) => [key, forms]),
])
const german = sorted([
	...[...singular].map(key => [key, de[key]]),
	...[...plurals].map(([key]) => [key, pluralDe[key]]),
])

await mkdir(path.join(root, 'l10n'), { recursive: true })
for (const [locale, translations, pluralForm] of [
	['en', english, 'nplurals=2; plural=(n != 1);'],
	['de', german, 'nplurals=2; plural=(n != 1);'],
]) {
	const payload = { translations, pluralForm }
	await writeFile(path.join(root, 'l10n', `${locale}.json`), `${JSON.stringify(payload, null, 2)}\n`)
	await writeFile(
		path.join(root, 'l10n', `${locale}.js`),
		`OC.L10N.register("proofing_gallery", ${JSON.stringify(translations, null, 2)}, "${pluralForm}");\n`,
	)
}

console.log(`Generated ${singular.size} singular and ${plurals.size} plural translations for en and de.`)
